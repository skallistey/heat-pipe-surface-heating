-- ========================================================
-- Heat Pipe Base Template
-- Factorio 2.1.7+
-- Используется как шаблон для всех уровней труб нагрева поверхности
-- ========================================================

-- Создаём копию стандартной трубы
-- table.deepcopy позволяет не трогать оригинальный прототип
local base = table.deepcopy(data.raw["heat-pipe"]["heat-pipe"])

-- Уникальное имя для новой трубы
-- Для следующих уровней трубы меняйте на: surface-heat-pipe-insulated, surface-heat-pipe-advanced и т.д.
base.name = "surface-heat-pipe-legendary"

-- Название предмета, который игрок получает при добыче
-- Для новых уровней трубы создавайте отдельный item
base.minable.result = "surface-heat-pipe-legendary"

-- ========================================================
-- Настройки нагрева территории
-- ========================================================

-- Радиус, который эта труба обогревает (в плитках)
-- Для следующих уровней трубы увеличиваем
base.heating_radius = 20

-- heating_energy здесь намеренно не задано: это собственная
-- энергия, необходимая сущности для защиты от замерзания, а не
-- мощность нагрева окружающих объектов. Радиус задаётся выше.

-- ========================================================
-- Визуальная часть
-- ========================================================

-- Иконка предмета (можно перекрашивать для разных уровней, если нужно)
base.icon = "__heat-pipe-surface-heating__/graphics/icons/heat-pipe-legendary.png"
base.icon_size = 128

-- Не трогаем sprite трубы, оставляем стандартный
-- Для будущих уровней можно перекрашивать через tint, но нужно проверять структуру base.pictures.layers

-- ========================================================
-- Завершение
-- ========================================================

-- Добавляем в список прототипов игры
data:extend({ base })
